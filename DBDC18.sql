-- TRIGGER 1
CREATE OR REPLACE TRIGGER TRG_VIGILANTE_BAJA
BEFORE DELETE ON VIGILANTE
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    -- Para cada día que cubría el vigilante eliminado,
    -- verificar que otro vigilante cubre ese turno ese día
    FOR r IN (SELECT Dia FROM DIAS WHERE DNI = :OLD.DNI) LOOP
        SELECT COUNT(*) INTO v_count
        FROM VIGILANTE V
        JOIN DIAS D ON V.DNI = D.DNI
        WHERE V.DNI != :OLD.DNI
        AND V.Turno = :OLD.Turno
        AND D.Dia = r.Dia;

        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 
                'No se puede eliminar el vigilante: el turno ' || :OLD.Turno || 
                ' del día ' || r.Dia || ' quedaría sin cubrir.');
        END IF;
    END LOOP;
END;
/

-- TRIGGER 2
CREATE OR REPLACE TRIGGER TRG_EMPLEADO_INTERNO_DNI
BEFORE INSERT OR UPDATE ON EMPLEADO_INTERNO
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    IF :NEW.Tipo = 'INSTRUCTOR' THEN
        SELECT COUNT(*) INTO v_count
        FROM INSTRUCTOR
        WHERE DNI = :NEW.DNI;

        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20003,
                'El DNI no corresponde a ningún instructor.');
        END IF;

    ELSIF :NEW.Tipo = 'VIGILANTE' THEN
        SELECT COUNT(*) INTO v_count
        FROM VIGILANTE
        WHERE DNI = :NEW.DNI;

        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20004,
                'El DNI no corresponde a ningún vigilante.');
        END IF;
    END IF;
END;
/

