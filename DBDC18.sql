CREATE TABLE GIMNASIO (
    ID NUMBER,
    Telefono VARCHAR2(15),
    Email VARCHAR2(100),
    Direccion VARCHAR2(200),
    Municipio VARCHAR2(100),
    Provincia VARCHAR2(100),
    AnoApertura NUMBER(4),
    CONSTRAINT PK_GYM PRIMARY KEY (ID)
);

CREATE TABLE CURSO (
    COD_Curso NUMBER,
    Nombre VARCHAR2(100),
    Especialidad VARCHAR2(100),
    Dificultad VARCHAR2(50),
    CONSTRAINT PK_CURSO PRIMARY KEY (COD_Curso)
);

CREATE TABLE PERSONA (
    DNI VARCHAR2(9),
    Nombre VARCHAR2(100),
    Telefono VARCHAR2(15),
    CONSTRAINT PK_PERSONA PRIMARY KEY (DNI)
);

CREATE TABLE SALA (
    ID NUMBER,
    Num_Sala NUMBER,
    Aforo NUMBER,
    CONSTRAINT PK_SALA PRIMARY KEY (ID, Num_Sala),
    CONSTRAINT FK_SALA_GYM FOREIGN KEY (ID) REFERENCES GIMNASIO(ID)
);

CREATE TABLE SALA_AEROBIC (
    ID NUMBER,
    Num_Sala NUMBER,
    Num_Esterillas NUMBER,
    CONSTRAINT PK_SALA_AEROBIC PRIMARY KEY (ID, Num_Sala),
    CONSTRAINT FK_SALA_AEROBIC_SALA FOREIGN KEY (ID, Num_Sala) REFERENCES SALA(ID, Num_Sala)
);

CREATE TABLE SALA_SPINNING (
    ID NUMBER,
    Num_Sala NUMBER,
    Num_Bicicletas NUMBER,
    CONSTRAINT PK_SALA_SPINNING PRIMARY KEY (ID, Num_Sala),
    CONSTRAINT FK_SALA_SPINNING_SALA FOREIGN KEY (ID, Num_Sala) REFERENCES SALA(ID, Num_Sala)
);

CREATE TABLE MIEMBRO (
    DNI VARCHAR2(9),
    Objetivo VARCHAR2(100),
    Nivel VARCHAR2(50),
    CONSTRAINT PK_MIEMBRO PRIMARY KEY (DNI),
    CONSTRAINT FK_MIEMBRO_PERSONA FOREIGN KEY (DNI) REFERENCES PERSONA(DNI)
);

CREATE TABLE INSTRUCTOR (
    DNI VARCHAR2(9),
    Especialidad VARCHAR2(100),
    CONSTRAINT PK_INSTRUCTOR PRIMARY KEY (DNI),
    CONSTRAINT FK_INSTRUCTOR_PERSONA FOREIGN KEY (DNI) REFERENCES PERSONA(DNI)
);

CREATE TABLE VIGILANTE (
    DNI VARCHAR2(9),
    Turno VARCHAR2(20),
    CONSTRAINT PK_VIGILANTE PRIMARY KEY (DNI),
    CONSTRAINT FK_VIGILANTE_PERSONA FOREIGN KEY (DNI) REFERENCES PERSONA(DNI)
);

CREATE TABLE EMPLEADO_INTERNO (
	DNI VARCHAR2(9),
	Salario NUMBER(8,2),
	Fecha_Contratacion DATE,
	Tipo VARCHAR2(10),
	CONSTRAINT PK_EMPLEADO_INTERNO PRIMARY KEY (DNI),
	CONSTRAINT FK_EMPLEADO_PERSONA FOREIGN KEY (DNI) REFERENCES PERSONA(DNI),
	CONSTRAINT CHK_TIPO CHECK (Tipo IN ('INSTRUCTOR', 'VIGILANTE'))
);

CREATE TABLE INSTRUCTOR_AFILIADO (
    DNI VARCHAR2(9),
    Descuento NUMBER(5,2),
    CONSTRAINT PK_INSTRUCTOR_AFILIADO PRIMARY KEY (DNI),
    CONSTRAINT FK_INS_AFIL_MIEMBRO FOREIGN KEY (DNI) REFERENCES MIEMBRO(DNI),
    CONSTRAINT FK_INS_AFIL_INSTRUCTOR FOREIGN KEY (DNI) REFERENCES INSTRUCTOR(DNI)
);

CREATE TABLE MEMBRESIA (
    ID NUMBER,
    Cod_Memb NUMBER,
    Tipo VARCHAR2(50),
    Precio_base NUMBER(8,2),
    DNI VARCHAR2(9) UNIQUE,
    Fecha_I DATE,
    Fecha_F DATE,
    CONSTRAINT PK_MEMBRESIA PRIMARY KEY (ID, Cod_Memb),
    CONSTRAINT FK_MEMBRESIA_GYM FOREIGN KEY (ID) REFERENCES GIMNASIO(ID),
    CONSTRAINT FK_MEMBRESIA_MIEMBRO FOREIGN KEY (DNI) REFERENCES MIEMBRO(DNI)
);

CREATE TABLE SESION (
    COD_Curso NUMBER,
    Num_Sesion NUMBER,
    Fecha DATE,
    Hora TIMESTAMP,
    Duracion NUMBER,
    ID NUMBER,
    Num_Sala NUMBER,
    CONSTRAINT PK_SESION PRIMARY KEY (COD_Curso, Num_Sesion),
    CONSTRAINT FK_SESION_CURSO FOREIGN KEY (COD_Curso) REFERENCES CURSO(COD_Curso),
    CONSTRAINT FK_SESION_SALA FOREIGN KEY (ID, Num_Sala) REFERENCES SALA(ID, Num_Sala)
);

CREATE TABLE CURSOENGYM (
    ID NUMBER,
    COD_Curso NUMBER,
    CONSTRAINT PK_CURSOENGYM PRIMARY KEY (ID, COD_Curso),
    CONSTRAINT FK_CURSOENGYM_GYM FOREIGN KEY (ID) REFERENCES GIMNASIO(ID),
    CONSTRAINT FK_CURSOENGYM_CURSO FOREIGN KEY (COD_Curso) REFERENCES CURSO(COD_Curso)
);

CREATE TABLE DIAS (
    DNI VARCHAR2(9),
    Dia VARCHAR2(10),
    CONSTRAINT PK_DIAS PRIMARY KEY (DNI, Dia),
    CONSTRAINT FK_DIAS_VIGILANTE FOREIGN KEY (DNI) REFERENCES VIGILANTE(DNI),
    CONSTRAINT CHK_DIA CHECK (Dia IN ('Lunes', 'Martes', 'Miercoles', 'Jueves', 'Viernes', 'Sabado', 'Domingo'))
);

CREATE TABLE ASISTENCIA (
    DNI VARCHAR2(9),
    COD_Curso NUMBER,
    Num_Sesion NUMBER,
    DNI_Instructor VARCHAR2(9) NOT NULL,
    CONSTRAINT PK_ASISTENCIA PRIMARY KEY (DNI, COD_Curso, Num_Sesion),
    CONSTRAINT FK_ASISTENCIA_MIEMBRO FOREIGN KEY (DNI) REFERENCES MIEMBRO(DNI),
    CONSTRAINT FK_ASISTENCIA_SESION FOREIGN KEY (COD_Curso, Num_Sesion) REFERENCES SESION(COD_Curso, Num_Sesion),
    CONSTRAINT FK_ASISTENCIA_INSTRUCTOR FOREIGN KEY (DNI_Instructor) REFERENCES INSTRUCTOR(DNI)
);

-- CURSOS EN MÁS DE UN GIMNASIO
CREATE VIEW CURSOS_MULTIGYM AS
SELECT
	C.COD_Curso,
	C.Nombre,
	C.Especialidad,
	C.Dificultad,
	COUNT(CG.ID) AS Num_Gimnasios
FROM CURSO C
JOIN CURSOENGYM CG ON C.COD_Curso = CG.COD_Curso
GROUP BY C.COD_Curso, C.Nombre, C.Especialidad, C.Dificultad
HAVING COUNT(CG.ID) > 1;

-- INSTRUCTORES AFILIADOS CON SUS DATOS, PRECIO DESCONTADO, Y GIMNASIO
CREATE VIEW INSTRUCTORES_AFILIADOS_DETALLE AS
SELECT 
    P.DNI,
    P.Nombre,
    P.Telefono,
    M.Objetivo,
    M.Nivel,
    I.Especialidad,
    ME.Cod_Memb,
    ME.Tipo AS Tipo_Membresia,
    ROUND(ME.Precio_base * (1 - IA.Descuento / 100), 2) AS Precio_con_Descuento,
    ME.Fecha_I,
    ME.Fecha_F,
    ME.ID AS ID_Gimnasio,
    G.Municipio AS Municipio_Gimnasio,
    G.Provincia AS Provincia_Gimnasio
FROM INSTRUCTOR_AFILIADO IA
JOIN PERSONA P ON IA.DNI = P.DNI
JOIN MIEMBRO M ON IA.DNI = M.DNI
JOIN INSTRUCTOR I ON IA.DNI = I.DNI
JOIN MEMBRESIA ME ON IA.DNI = ME.DNI
JOIN GIMNASIO G ON ME.ID = G.ID;

